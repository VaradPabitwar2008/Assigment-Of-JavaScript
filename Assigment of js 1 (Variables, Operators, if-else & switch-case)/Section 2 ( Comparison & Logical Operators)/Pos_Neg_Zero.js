
// 7. Positive, Negative or Zero
// Take a number and determine whether it is:
// ● Positive
// ● Negative
// ● Zero

let num = 1; 

if (num > 0){
    console.log(num, "is Positive Number");
}else if(num < 0){
    console.log(num, "is Negative Number"); 
}else{
    console.log(num, "is Zero Number");
}
